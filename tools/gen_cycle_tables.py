"""RONDO: the decay tables of the CYCLE engines (eng_cycle.c), printed as C to paste into it.
CYC_KB[i]: the per-block (CTL = 32 samples at 44.1 kHz) multiplier, Q30, of an exponential decay that falls
60 dB in T(i) = 2 ms * 2^(i / 12): i = 0 2 ms, 12 4 ms, .. 132 4.1 s, 143 7.8 s (a doubling every 12 steps,
so a decay time scaled by 2^(k / 12) is the index + k)."""
import math
FS, CTL, N = 44100, 32, 144
rows = []
print("/* SPDX-License-Identifier: GPL-3.0-only\n * Copyright (C) 2026 Dungeon Tracker (RONDO) contributors. Built on Felucca (C) 2026 Leo Kuroshita (@kurogedelic), Hügelton Instruments */")
print("/* generated by tools/gen_cycle_tables.py */")
for i in range(N):
    t = 0.002 * 2 ** (i / 12)
    k = 10 ** (-3 * CTL / (t * FS))
    rows.append(int(round(k * (1 << 30))))
print(f"#define CYC_NKB {N}")
print("static const int32_t CYC_KB[CYC_NKB] = {   /* tools/gen_cycle_tables.py */")
for j in range(0, N, 8):
    print("    " + ", ".join(f"{v}" for v in rows[j:j + 8]) + ",")
print("};")
